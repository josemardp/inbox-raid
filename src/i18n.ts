const dict: Record<Lang, Record<Key, string>> = { en, pt };

function detect(): Lang {
  try {
    const saved = localStorage.getItem('inbox-raid-lang');
    if (saved === 'en' || saved === 'pt') return saved;
  } catch { /* storage blocked */ }
  return /^pt\b/i.test(navigator.language || '') ? 'pt' : 'en';
}

export let lang: Lang = typeof navigator === 'undefined' ? 'en' : detect();

/** A string in the current language, with {name} placeholders filled. */
export function t(key: Key, vars: Record<string, string | number> = {}): string {
  return dict[lang][key].replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ''));
}

export function setLang(l: Lang) {
  lang = l;
  try { localStorage.setItem('inbox-raid-lang', l); } catch { /* storage blocked */ }
  document.documentElement.lang = l === 'pt' ? 'pt-BR' : 'en';
}

/** Number format that follows the language (1,460 or 1.460). */
export const fmt = (n: number) => Math.round(n).toLocaleString(lang === 'pt' ? 'pt-BR' : 'en-US');

